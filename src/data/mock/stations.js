export const STATIONS = RAW_STATIONS.map((raw) => {
  const cpcb = calculateCPCBAQI(raw.pollutants);
  const epa = calculateEPAAQI(raw.pollutants);
  const defaultStandard =
    raw.country === 'India' ? AQI_STANDARDS.CPCB_NAQI : AQI_STANDARDS.US_EPA;
  const primaryResult = defaultStandard === AQI_STANDARDS.CPCB_NAQI ? cpcb : epa;

  return {
    ...raw,
    id: raw.stationId,
    timestamp: DEMO_TIMESTAMP,
    source: DEMO_SOURCE,
    dataType: 'simulated',
    methodology: defaultStandard,
    aqi: primaryResult.aqi,
    aqiByStandard: {
      [AQI_STANDARDS.CPCB_NAQI]: cpcb,
      [AQI_STANDARDS.US_EPA]: epa,
    },
  };
});

export function computeStationForStandard(station, standard) {
  const std = standard || station.methodology || AQI_STANDARDS.CPCB_NAQI;
  const result = station.aqiByStandard?.[std] || calculateCPCBAQI(station.pollutants);
  return {
    ...station,
    methodology: std,
    aqi: result.aqi,
    category: result.category,
    dominantPollutant: result.dominantPollutant,
    subIndices: result.subIndices,
    aqiEvaluation: result,
  };
}
